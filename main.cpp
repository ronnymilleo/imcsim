#include "application.h"
#include "error_codes.h"

// Main code
int main(int, char **) {
    GUI::Application app;
    int result = app.Init();
    if (result == Core::ExitSuccess) {
        result = app.Run();
    }
    app.Shutdown();
    return result;
}

